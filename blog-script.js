// المنت‌ها
const postsList = document.getElementById('postsList');
const singlePost = document.getElementById('singlePost');
const backToListBtn = document.getElementById('backToList');

// بررسی هش لینک برای نمایش مستقیم مقاله
function checkHash() {
    const hash = window.location.hash;
    if (hash.startsWith('#post-')) {
        const postId = hash.replace('#post-', '');
        if (postsData[postId]) {
            showPost(postId);
        }
    }
}

// نمایش مقاله
function showPost(postId) {
    const post = postsData[postId];
    if (post) {
        document.getElementById('singleTitle').innerHTML = post.title;
        document.getElementById('singleContent').innerHTML = post.content;
        postsList.classList.add('hide');
        singlePost.classList.add('active');
        window.scrollTo({ top: 0, behavior: 'smooth' });
    }
}

// بازگشت به لیست مقالات
function showPostsList() {
    postsList.classList.remove('hide');
    singlePost.classList.remove('active');
    window.location.hash = '';
}

// رویدادهای کلیک روی کارت مقاله
document.querySelectorAll('.post-card').forEach(card => {
    card.addEventListener('click', (e) => {
        if (e.target.classList.contains('read-more')) {
            e.stopPropagation();
        }
        const postId = card.getAttribute('data-post');
        showPost(postId);
        window.location.hash = `post-${postId}`;
    });
});

// رویداد برای لینک "ادامه مطلب"
document.querySelectorAll('.read-more').forEach(link => {
    link.addEventListener('click', (e) => {
        e.stopPropagation();
        const card = link.closest('.post-card');
        const postId = card.getAttribute('data-post');
        showPost(postId);
        window.location.hash = `post-${postId}`;
    });
});

// بازگشت به لیست
backToListBtn.addEventListener('click', () => {
    showPostsList();
});

// بررسی هش هنگام لود صفحه
checkHash();
